#!/usr/bin/env python3
"""Generate responsive WebP versions of everything in /Images and record sizes in _data/images.yml.

Originals are never modified or removed (they stay the downloadable full-quality versions).
Small originals (<= 1000 px wide and <= 150 KB) get no variants: they are already light.

Usage (from the repo root, with Pillow installed):
    python _maintenance/portfolio-overhaul/tools/optimise_images.py

Output:
    Images/optimised/<name>-<width>.webp
    _data/images.yml          {"/Images/<file>": {w, h, bytes, webp: [{w, src}, ...]}}
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "Images"
OUT = SRC / "optimised"
DATA = ROOT / "_data" / "images.yml"
WIDTHS = [480, 800, 1200, 1600]
SKIP_SMALL_W, SKIP_SMALL_BYTES = 1000, 150 * 1024
EXTS = {".jpg", ".jpeg", ".png", ".webp"}
SVG_ROOTS = [ROOT / "assets"]   # SVGs are catalogued for their dimensions only (they need no variants)


def svg_size(path: Path):
    """Width/height of an SVG from its width/height attributes, else its viewBox."""
    head = path.read_text(encoding="utf-8", errors="replace")[:2000]
    w = re.search(r'\swidth="([\d.]+)(?:px)?"', head)
    h = re.search(r'\sheight="([\d.]+)(?:px)?"', head)
    if w and h:
        return round(float(w.group(1))), round(float(h.group(1)))
    vb = re.search(r'viewBox="[-\d.]+[ ,]+[-\d.]+[ ,]+([\d.]+)[ ,]+([\d.]+)"', head)
    if vb:
        return round(float(vb.group(1))), round(float(vb.group(2)))
    return None


def main() -> int:
    OUT.mkdir(exist_ok=True)
    entries: dict[str, dict] = {}
    for p in sorted(SRC.iterdir()):
        if not p.is_file() or p.suffix.lower() not in EXTS:
            continue
        with Image.open(p) as im:
            im = ImageOps.exif_transpose(im)
            w, h = im.size
            size = p.stat().st_size
            rec: dict = {"w": w, "h": h, "bytes": size}
            small = w <= SKIP_SMALL_W and size <= SKIP_SMALL_BYTES
            variants = []
            if not small:
                widths = [x for x in WIDTHS if x < w] + [w if w <= 2000 else 2000]
                for tw in sorted(set(widths)):
                    name = f"{p.stem}-{tw}.webp"
                    target = OUT / name
                    if not target.exists() or target.stat().st_mtime < p.stat().st_mtime:
                        copy = im.convert("RGBA") if im.mode in ("P", "LA") else im
                        if copy.mode not in ("RGB", "RGBA"):
                            copy = copy.convert("RGB")
                        resized = copy if tw == w else copy.resize((tw, round(h * tw / w)), Image.LANCZOS)
                        # Line drawings / FEA plots with flat colour compress better losslessly at small sizes.
                        resized.save(target, "WEBP", quality=82, method=6)
                    variants.append({"w": tw, "src": f"/Images/optimised/{name}"})
            if variants:
                rec["webp"] = variants
            entries[f"/Images/{p.name}"] = rec

    for root in SVG_ROOTS:
        for svg in sorted(root.rglob("*.svg")):
            size = svg_size(svg)
            if size:
                entries["/" + svg.relative_to(ROOT).as_posix()] = {"w": size[0], "h": size[1], "bytes": svg.stat().st_size}

    lines = [
        "# Generated by _maintenance/portfolio-overhaul/tools/optimise_images.py. Do not edit by hand;",
        "# re-run the script after adding or replacing an image in /Images.",
    ]
    for key, rec in entries.items():
        lines.append(f'"{key}":')
        lines.append(f"  w: {rec['w']}")
        lines.append(f"  h: {rec['h']}")
        lines.append(f"  bytes: {rec['bytes']}")
        if "webp" in rec:
            lines.append("  webp:")
            for v in rec["webp"]:
                lines.append(f'    - {{ w: {v["w"]}, src: "{v["src"]}" }}')
    DATA.write_text("\n".join(lines) + "\n", encoding="utf-8")

    total_o = sum(r["bytes"] for r in entries.values())
    total_n = 0
    for r in entries.values():
        for v in r.get("webp", []):
            total_n += (ROOT / v["src"].lstrip("/")).stat().st_size
    print(f"{len(entries)} images catalogued; variants written to {OUT.relative_to(ROOT)}")
    print(f"originals total {total_o // 1024} KB; generated variants total {total_n // 1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
